    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (!validarCampos()) return;
    String sql = "INSERT INTO Producto (codigo, nombre, categoria, precio, stock) VALUES (?, ?, ?, ?, ?)";
    try (Connection con = Conexion.conectar(); PreparedStatement pst = con.prepareStatement(sql)) {
        pst.setString(1, txtCodigo.getText().trim());
        pst.setString(2, txtNombre.getText().trim());
        pst.setString(3, txtCategoria.getText().trim());
        pst.setDouble(4, Double.parseDouble(txtPrecio.getText().trim()));
        pst.setInt(5, Integer.parseInt(txtStock.getText().trim()));
        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "¡Producto guardado exitosamente!");
        listarProductos();
        limpiarFormulario();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

