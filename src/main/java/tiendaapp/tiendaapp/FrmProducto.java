    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       if (idSeleccionado == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla para eliminar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }
    int confirmacion = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este producto?", "Confirmar", JOptionPane.YES_NO_OPTION);
    if (confirmacion == JOptionPane.YES_OPTION) {
        String sql = "DELETE FROM Producto WHERE id = ?";
        try (Connection con = Conexion.conectar(); PreparedStatement pst = con.prepareStatement(sql)) {
            pst.setInt(1, idSeleccionado);
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "¡Producto eliminado exitosamente!");
            listarProductos();
            limpiarFormulario();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
       if (idSeleccionado == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla para modificar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }
    if (!validarCampos()) return;
    String sql = "UPDATE Producto SET codigo = ?, nombre = ?, categoria = ?, precio = ?, stock = ? WHERE id = ?";
    try (Connection con = Conexion.conectar(); PreparedStatement pst = con.prepareStatement(sql)) {
        pst.setString(1, txtCodigo.getText().trim());
        pst.setString(2, txtNombre.getText().trim());
        pst.setString(3, txtCategoria.getText().trim());
        pst.setDouble(4, Double.parseDouble(txtPrecio.getText().trim()));
        pst.setInt(5, Integer.parseInt(txtStock.getText().trim()));
        pst.setInt(6, idSeleccionado);
        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "¡Producto modificado exitosamente!");
        listarProductos();
        limpiarFormulario();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al modificar: " + e.getMessage());
    }
    }//GEN-LAST:event_btnModificarActionPerformed

